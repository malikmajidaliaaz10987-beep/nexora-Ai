/**
 * NEXORA AI — Modular Server-Side AI Service Layer
 * Connects Google GenAI SDK (gemini-3.8-flash) with atomic credit accounting,
 * latency logging, and specialized studio orchestration.
 */

import { GoogleGenAI } from '@google/genai';
import { db } from './db.js';

// Lazy initialize Google GenAI SDK
let aiClient: GoogleGenAI | null = null;

function getAIClient(): GoogleGenAI {
  if (!aiClient) {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      console.warn('GEMINI_API_KEY is not set in environment. Gemini features will return informative guidance.');
    }
    aiClient = new GoogleGenAI();
  }
  return aiClient;
}

export interface StudioGenerationRequest {
  userId: string;
  studio: 'writing' | 'image' | 'video' | 'document' | 'chatbot' | 'marketing' | 'business';
  tool: string;
  prompt: string;
  parameters?: Record<string, any>;
  creditCost?: number;
}

export interface StudioGenerationResult {
  success: boolean;
  output?: string;
  data?: any;
  error?: string;
  creditsUsed: number;
  remainingCredits: number;
  latencyMs: number;
}

/**
 * Executes a verified AI studio prompt with server-side credit deduction and error refund
 */
export async function executeStudioAI(req: StudioGenerationRequest): Promise<StudioGenerationResult> {
  const creditCost = req.creditCost || 10;
  const startTime = Date.now();

  // 1. Atomic credit deduction
  const deduction = db.deductCredits(
    req.userId,
    creditCost,
    `${req.studio}_${req.tool}`,
    `${req.studio.toUpperCase()} Studio: ${req.tool}`
  );

  if (!deduction.success) {
    return {
      success: false,
      error: deduction.error || 'Insufficient credits to perform this AI generation.',
      creditsUsed: 0,
      remainingCredits: deduction.balance,
      latencyMs: Date.now() - startTime
    };
  }

  try {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      // Refund credits
      const refundedBalance = db.refundCredits(
        req.userId,
        creditCost,
        'API key configuration pending on server'
      );
      return {
        success: false,
        error: 'GEMINI_API_KEY is not configured on the server. Please configure it in .env or the Secrets panel.',
        creditsUsed: 0,
        remainingCredits: refundedBalance,
        latencyMs: Date.now() - startTime
      };
    }

    const ai = getAIClient();
    const systemInstruction = buildSystemPrompt(req.studio, req.tool, req.parameters);

    const userContent = formatUserPrompt(req.tool, req.prompt, req.parameters);

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: userContent,
      config: {
        systemInstruction,
        temperature: getTemperatureForStudio(req.studio),
        maxOutputTokens: 2500,
      }
    });

    const latencyMs = Date.now() - startTime;
    const outputText = response.text || 'No response generated by model.';

    // Record generation
    db.recordGeneration({
      user_id: req.userId,
      studio: req.studio,
      tool: req.tool,
      prompt: req.prompt,
      parameters: req.parameters || {},
      output: outputText,
      credits_used: creditCost,
      status: 'completed'
    });

    // Record usage log
    db.recordUsageLog({
      user_id: req.userId,
      provider: 'Google Gemini',
      model: 'gemini-3.8-flash',
      tokens_input: Math.ceil(userContent.length / 4),
      tokens_output: Math.ceil(outputText.length / 4),
      latency_ms: latencyMs,
      status: 'success'
    });

    return {
      success: true,
      output: outputText,
      creditsUsed: creditCost,
      remainingCredits: deduction.balance,
      latencyMs
    };
  } catch (err: any) {
    const latencyMs = Date.now() - startTime;
    console.error('AI Studio execution error:', err);

    // Refund credits on failure
    const refundedBalance = db.refundCredits(
      req.userId,
      creditCost,
      `API execution failed: ${err.message || 'Unknown error'}`
    );

    // Record failure log
    db.recordUsageLog({
      user_id: req.userId,
      provider: 'Google Gemini',
      model: 'gemini-3.8-flash',
      tokens_input: 0,
      tokens_output: 0,
      latency_ms: latencyMs,
      status: 'error',
      error_message: err.message || String(err)
    });

    return {
      success: false,
      error: `Generation failed: ${err.message || 'Internal AI engine error'}. Your ${creditCost} credits were refunded.`,
      creditsUsed: 0,
      remainingCredits: refundedBalance,
      latencyMs
    };
  }
}

/**
 * Specialized system prompts for each of the 7 Studios
 */
function buildSystemPrompt(studio: string, tool: string, params?: Record<string, any>): string {
  const baseInstruction = 'You are NEXORA AI, the world-class SaaS intelligence workspace engine. Provide highly structured, professional, ready-to-use output. Never include meta conversational chit-chat like "Sure, here is your..." or "I hope this helps". Deliver the clean, polished content directly in clean Markdown format with headers, lists, and formatting.';

  switch (studio) {
    case 'writing':
      return `${baseInstruction}
You are operating in the NEXORA AI WRITING STUDIO.
Tool: ${tool}.
Target Tone: ${params?.tone || 'Professional & Compelling'}.
Target Audience: ${params?.audience || 'General Business / Creators'}.
Language: ${params?.language || 'English'}.
Length Target: ${params?.length || 'Medium'}.
Provide complete, actionable, high-conversion copy.`;

    case 'document':
      return `${baseInstruction}
You are operating in the NEXORA AI DOCUMENT STUDIO.
Tool: ${tool}.
Analyze provided text/documents with deep analytical rigor. Pull out key statistics, executive summaries, risk items, and actionable takeaways. Format with clear headings and bulleted takeaways.`;

    case 'chatbot':
      return `${baseInstruction}
You are operating in the NEXORA AI CHATBOT ENGINE.
Persona: ${params?.systemPrompt || 'Helpful customer service concierge'}.
Knowledge base context:
${params?.knowledgeContext || 'No custom knowledge context provided.'}
Rules:
1. Answer using the provided knowledge base context whenever relevant.
2. If the user asks something outside the knowledge base, answer courteously and suggest connecting with a human representative if appropriate.`;

    case 'marketing':
      return `${baseInstruction}
You are operating in the NEXORA AI MARKETING STUDIO.
Tool: ${tool}.
Target Platform / Channel: ${params?.channel || 'Omnichannel'}.
Goal: Maximize engagement, CTR, brand affinity, and conversions. Include clear Hooks, Value Propositions, Calls to Action (CTA), and recommended hashtag or keyword clusters.`;

    case 'business':
      return `${baseInstruction}
You are operating in the NEXORA AI BUSINESS ASSISTANT.
Tool: ${tool}.
For business plans, provide Executive Summary, Market Analysis, Revenue Model, Competitive Advantage, and Milestones.
For meeting notes, extract Action Items, Key Decisions, and Owner Matrix.
For project planning, produce structured tasks with estimation, priority, and phase breakdowns.`;

    default:
      return baseInstruction;
  }
}

function formatUserPrompt(tool: string, prompt: string, params?: Record<string, any>): string {
  let details = `Task: ${tool}\nPrimary Brief/Topic:\n${prompt}\n`;
  if (params?.keywords) details += `\nRequired Keywords: ${params.keywords}`;
  if (params?.targetAudience) details += `\nTarget Audience: ${params.targetAudience}`;
  if (params?.format) details += `\nDesired Format: ${params.format}`;
  if (params?.sourceText) details += `\nReference Source Document / Text:\n"""\n${params.sourceText}\n"""`;
  return details;
}

function getTemperatureForStudio(studio: string): number {
  switch (studio) {
    case 'writing': return 0.7;
    case 'marketing': return 0.75;
    case 'chatbot': return 0.5;
    case 'document': return 0.2;
    case 'business': return 0.3;
    default: return 0.5;
  }
}

/**
 * Deterministic business calculations (invoices, quotations, tax, profit margins)
 * Section 6: "For financial and business calculations, use validated deterministic calculations rather than relying solely on AI-generated numbers."
 */
export function calculateBusinessDocument(items: Array<{ description: string; quantity: number; unitPrice: number }>, taxRatePercent: number = 0, discountPercent: number = 0) {
  const subtotal = items.reduce((sum, item) => sum + (Number(item.quantity) * Number(item.unitPrice)), 0);
  const discountAmount = (subtotal * (discountPercent / 100));
  const subtotalAfterDiscount = subtotal - discountAmount;
  const taxAmount = (subtotalAfterDiscount * (taxRatePercent / 100));
  const grandTotal = subtotalAfterDiscount + taxAmount;

  return {
    items: items.map(item => ({
      ...item,
      lineTotal: Number(item.quantity) * Number(item.unitPrice)
    })),
    subtotal: Math.round(subtotal * 100) / 100,
    discountPercent,
    discountAmount: Math.round(discountAmount * 100) / 100,
    taxRatePercent,
    taxAmount: Math.round(taxAmount * 100) / 100,
    grandTotal: Math.round(grandTotal * 100) / 100
  };
}

/**
 * Checks live provider status for admin and studios
 */
export function getAIProviderStatus() {
  const geminiKey = process.env.GEMINI_API_KEY;
  const imageKey = process.env.IMAGE_PROVIDER_API_KEY;
  const videoKey = process.env.VIDEO_PROVIDER_API_KEY;
  const voiceKey = process.env.VOICE_PROVIDER_API_KEY;

  return {
    gemini: {
      provider: 'Google Gemini',
      model: 'gemini-3.8-flash',
      configured: Boolean(geminiKey),
      status: geminiKey ? 'active' : 'needs_configuration',
      capabilities: ['writing', 'documents', 'chatbots', 'marketing', 'business_analysis']
    },
    image: {
      provider: 'Imagen 3 / External Image API',
      configured: Boolean(imageKey || geminiKey),
      status: (imageKey || geminiKey) ? 'ready' : 'needs_configuration',
      capabilities: ['text_to_image', 'variations', 'background_removal']
    },
    video: {
      provider: 'Video Pipeline Service',
      configured: Boolean(videoKey),
      status: videoKey ? 'ready' : 'needs_configuration',
      capabilities: ['text_to_video', 'image_to_video', 'storyboarding']
    },
    voice: {
      provider: 'Audio / Voiceover Engine',
      configured: Boolean(voiceKey),
      status: voiceKey ? 'ready' : 'needs_configuration',
      capabilities: ['ai_voiceover', 'speech_synthesis']
    }
  };
}
